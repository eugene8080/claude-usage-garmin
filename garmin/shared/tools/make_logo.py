"""Builds the app logo: Claude, Codex and Cursor as three 120-degree wedges of one circle.

Settings are Eugene's from docs/watch-glance-editor/glance-editor.html (2026-11-13):
rotation 42, gap 20 (in the editor's 200-unit box), circle, order Claude/Codex/Cursor,
brand marks off. Writes:

  garmin/shared/resources-round-454x454/drawables/launcher_icon.png   (65 x 65, Garmin launcher)
  app/src/main/res/drawable/ic_launcher_foreground.xml               (Android adaptive icon)

Run from anywhere:  python garmin/shared/tools/make_logo.py
The wedge geometry is computed once here, so the Android vector holds plain polygons and
needs no clip paths (older Android vector renderers handle clip paths badly).
"""
import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[3]

ROT = 42.0                 # degrees, clockwise from 12 o'clock (editor convention)
GAP = 20.0                 # seam width in the 200-unit box
R = 98.0                   # circle radius in that box
COLOURS = ["#D97757", "#8CA0FF", "#EDEDED"]   # Claude, Codex, Cursor
SEAM = "#0B0B0D"


def unit(deg: float) -> tuple[float, float]:
    """Direction for an editor angle (0 = up, clockwise), in y-down screen coordinates."""
    a = math.radians(deg - 90)
    return math.cos(a), math.sin(a)


def wedge_polygon(a0: float, a1: float, step: float = 2.0) -> list[tuple[float, float]]:
    """One wedge, with each straight edge pulled GAP/2 inside, clipped to the circle.

    The apex moves out along the wedge bisector so both edges keep a GAP/2 clearance.
    Points are relative to the circle centre (0, 0).
    """
    half = GAP / 2.0
    mid = (a0 + a1) / 2.0
    # Apex distance along the bisector: the edges sit 60 degrees either side of it.
    apex_d = half / math.sin(math.radians(60.0))
    ax, ay = unit(mid)
    apex = (ax * apex_d, ay * apex_d)

    pts = [apex]
    # Start of the arc: where the offset edge at a0 meets the circle.
    def edge_hit(edge_deg: float) -> float:
        """Angle (deg) on the circle where the edge offset by `half` toward the wedge meets it."""
        # Offset edge: points at perpendicular distance `half` from the edge ray, inside the wedge.
        # On the circle that is an angle shift of asin(half / R) toward the wedge.
        shift = math.degrees(math.asin(half / R))
        return edge_deg + shift if edge_deg == a0 else edge_deg - shift

    s, e = edge_hit(a0), edge_hit(a1)
    n = max(2, int(math.ceil((e - s) / step)))
    for i in range(n + 1):
        d = s + (e - s) * i / n
        ux, uy = unit(d)
        pts.append((ux * R, uy * R))
    return pts


def polygons() -> list[list[tuple[float, float]]]:
    return [wedge_polygon(ROT + i * 120.0, ROT + (i + 1) * 120.0) for i in range(3)]


def write_png(path: Path, size: int = 65, ss: int = 16) -> None:
    """Draw at 16x then average down, so the 65 px edges are smooth."""
    big = size * ss
    scale = big / 200.0
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    for poly, col in zip(polygons(), COLOURS):
        d.polygon([(100 * scale + x * scale, 100 * scale + y * scale) for x, y in poly], fill=col)
    img = img.resize((size, size), Image.LANCZOS)
    img.save(path)


def write_android(path: Path) -> None:
    """Adaptive-icon foreground: 108 viewport, circle diameter 66 (the safe zone)."""
    k = 66.0 / (2 * R)
    lines = [
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
        "",
        "    <!--",
        "      Three wedges of one circle: Claude, Codex and Cursor, in their brand colours, with a",
        "      dark seam between them. Generated by garmin/shared/tools/make_logo.py from the settings",
        "      in docs/watch-glance-editor/glance-editor.html; edit the script, not this file.",
        "    -->",
    ]
    for poly, col in zip(polygons(), COLOURS):
        pts = [(54 + x * k, 54 + y * k) for x, y in poly]
        d = "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + " Z"
        lines.append(f'    <path android:fillColor="{col}" android:pathData="{d}" />')
    lines.append("</vector>")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    png = ROOT / "garmin/shared/resources-round-454x454/drawables/launcher_icon.png"
    xml = ROOT / "app/src/main/res/drawable/ic_launcher_foreground.xml"
    write_png(png)
    write_android(xml)
    assert png.stat().st_size > 0 and xml.stat().st_size > 0
    print("wrote", png, "and", xml)
